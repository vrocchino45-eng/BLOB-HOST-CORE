import fs from "node:fs";
import assert from "node:assert/strict";
const read = (p) => fs.readFileSync(p,"utf8");
const json = (p) => JSON.parse(read(p));
const manifest = json("public/data/build/buildManifest.json");
const profile = json(manifest.id === "HC-014I" ? "public/data/runtime/act1RuntimeProfile_HC014I.json" : manifest.id === "HC-014G" ? "public/data/runtime/act1RuntimeProfile_HC014G.json" : manifest.id === "HC-014F" ? "public/data/runtime/act1RuntimeProfile_HC014F.json" : manifest.id === "HC-014E" ? "public/data/runtime/act1RuntimeProfile_HC014E.json" : manifest.id === "HC-014D" ? "public/data/runtime/act1RuntimeProfile_HC014D.json" : "public/data/runtime/act1RuntimeProfile_HC014C.json");
const gates = json("public/data/gates/firstSliceGates_HC006I.json");
assert.ok(["HC-014C", "HC-014D", "HC-014E", "HC-014F", "HC-014G", "HC-014I"].includes(manifest.id));
assert.equal(manifest.version, manifest.id === "HC-014I" ? "0.0.142" : manifest.id === "HC-014G" ? "0.0.140" : manifest.id === "HC-014F" ? "0.0.139" : manifest.id === "HC-014E" ? "0.0.138" : manifest.id === "HC-014D" ? "0.0.137" : "0.0.136");
assert.equal(profile.id, manifest.id === "HC-014I" ? "ACT1_RUNTIME_PROFILE_HC014G" : manifest.id === "HC-014G" ? "ACT1_RUNTIME_PROFILE_HC014G" : manifest.id === "HC-014F" ? "ACT1_RUNTIME_PROFILE_HC014F" : manifest.id === "HC-014E" ? "ACT1_RUNTIME_PROFILE_HC014E" : manifest.id === "HC-014D" ? "ACT1_RUNTIME_PROFILE_HC014D" : "ACT1_RUNTIME_PROFILE_HC014C");
assert.equal(profile.pass, manifest.id);
const comb = gates.find(g=>g.id==="hub_to_comb_threshold");
const aperture = gates.find(g=>g.id==="comb_threshold_to_aperture_fields");
assert.equal(comb.interactionRange,1.75);
assert.equal(aperture.interactionRange,2.15);
const hub = read("src/hub/HubChamberFoundationSystem.js");
assert.match(hub,/postConvergenceQuieting/);
assert.match(hub,/combInside/);
assert.match(hub,/combNear/);
const overlay=read("src/debug/RecipeDebugOverlay.js");
assert.match(overlay,/GATE PROXIMITY dist:/);
assert.match(overlay,/Gate eligibility awake:/);
const gateSystem=read("src/systems/GateSystem.js");
assert.match(gateSystem,/interactionDistance: interaction\.distance/);
assert.match(gateSystem,/interactionReady: interaction\.ready/);
assert.match(gateSystem,/expectedInput: interaction\.expectedInput/);
console.log(`${manifest.id} progression readability validation passed.`);
