import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
const root=process.cwd();
const j=(p)=>JSON.parse(fs.readFileSync(path.join(root,p),"utf8"));
const t=(p)=>fs.readFileSync(path.join(root,p),"utf8");
const manifest=j("public/data/build/buildManifest.json");
const recipe=j("public/data/thresholds/combThresholdPlayable_HC013B.json");
const foundation=j("public/data/thresholds/combThresholdFoundation_HC013A.json");
const profile=j("public/data/runtime/act1RuntimeProfile_HC014I.json");
assert.ok(["HC-014G","HC-014I"].includes(manifest.id));
assert.equal(manifest.version, manifest.id === "HC-014I" ? "0.0.142" : "0.0.140");
assert.equal(profile.id, manifest.id === "HC-014I" ? "ACT1_RUNTIME_PROFILE_HC014G" : manifest.id === "HC-014G" ? "ACT1_RUNTIME_PROFILE_HC014G" : "ACT1_RUNTIME_PROFILE_HC014G");
assert.equal(profile.pass, manifest.id === "HC-014I" ? "HC-014I" : "HC-014G");
const bands=recipe.interaction.filterBandZ;
assert.equal(bands.length,6);
assert.equal(bands[5],foundation.anatomy.finalFilterCenterZ);
assert.ok(recipe.interaction.finalBandRange < recipe.interaction.bandRange,"final filter must be tighter than earlier bands");
const sealZ=foundation.apertureDestinationContract.sealPosition[2];
const frontEdge=sealZ + foundation.apertureDestinationContract.sealReadRange;
const sixthBackEdge=bands[5]-recipe.interaction.finalBandRange;
assert.ok(sixthBackEdge >= frontEdge,`filter 6 (${sixthBackEdge}) must not penetrate seal interaction front edge (${frontEdge})`);
assert.equal(foundation.apertureDestinationContract.membraneAwakensAfterFilterReads,6);
const src=t("src/thresholds/CombThresholdFoundationSystem.js");
assert.match(src,/apertureSealRoot\.visible = membraneAwake/);
assert.match(src,/finalFilterStationZ/);
const play=t("src/thresholds/CombThresholdPlayableSystem.js");
assert.match(play,/finalBandRange/);
assert.match(play,/currentBandRange/);
console.log("HC-014F Comb endpoint separation validation passed.");
