import assert from 'node:assert/strict';
import * as THREE from 'three';
import { SignalPlainEcologySystem } from '../src/fields/SignalPlainEcologySystem.js';
import { DebugAreaJumpSystem } from '../src/debug/DebugAreaJumpSystem.js';
import fs from 'node:fs';
const scene=new THREE.Scene(), playerRoot=new THREE.Group(); scene.add(playerRoot);
const frameState={frame:1,runtimeSeconds:0,activeCellId:'CELL_APERTURE_FIELDS_ARRIVAL_001',input:{}};
const sys=new SignalPlainEcologySystem({scene,playerRoot,frameState}); sys.onRuntimeMount(frameState);
frameState.debugSignalPlainJumpRequest={pending:true,resetEncounter:true,requestedAtFrame:1}; sys.update(1/60,frameState);
assert.equal(frameState.debugAreaJump.signalPlainApproachStaged,true);
assert.ok(frameState.signalPlainEcology.signalPlainDistance > 8.5 && frameState.signalPlainEcology.signalPlainDistance < 10.5, 'direct spawn must be an approach, not inside organ');
assert.equal(frameState.signalPlainEcology.observedCount,0);
const positions=sys.nodes.map(n=>n.group.position.clone());
for(let i=0;i<positions.length;i++) for(let j=i+1;j<positions.length;j++) assert.ok(positions[i].distanceTo(positions[j])>6.0,'receptors need spatial separation');
assert.equal(frameState.interactionInspectionFocus.providerId,'SignalPlainEcologySystem');
assert.equal(frameState.interactionInspectionFocus.active,true);
const arrival=fs.readFileSync(new URL('../src/fields/ApertureFieldsArrivalSystem.js',import.meta.url),'utf8');
for(const marker of ['inspectionFadeable','aperture_midfield_connective_','aperture_macro_context_tissue']) assert.ok(arrival.includes(marker),marker);
const debug=new DebugAreaJumpSystem(); frameState.frame=2; frameState.input={debugJumpSlot:8,debugJumpDirect:true}; debug.update(0,frameState);
assert.equal(frameState.debugSignalPlainJumpRequest.pending,true);
assert.equal(frameState.debugAreaJump.pass,'HC-015C');
console.log('PASS HC-015C Signal Plain play-space correction');
